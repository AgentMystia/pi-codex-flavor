test('Codex session approvals cache exact commands, never denials, and stay memory-only', async t => {
  const dialogs = [];
  const f = await fixture(t, { config: { approval: 'on-request' }, ui: { available: true, select: async (_title, labels) => { dialogs.push(labels); return labels[1]; } } });
  const approved = await f.runtime.executor.exec({ cmd: 'printf trusted', require_approval: true, yield_time_ms: 1000 });
  assert.equal(approved.exit_code, 0); assert.equal(dialogs.length, 1);
  const cached = await f.runtime.executor.exec({ cmd: 'printf trusted', require_approval: true, yield_time_ms: 1000 });
  assert.equal(cached.exit_code, 0); assert.equal(dialogs.length, 1, 'the exact approved command skips the dialog for the session');
  assert.ok(f.runtime.state.data.approvals.some(record => record.source === 'session-cache' && record.scope === 'session'), 'cache hits record their source and scope');
  const varied = await f.runtime.executor.exec({ cmd: 'printf trusted again', require_approval: true, yield_time_ms: 1000 });
  assert.equal(varied.exit_code, 0); assert.equal(dialogs.length, 2, 'changed arguments prompt again like the Codex exact-match cache');
  const records = f.runtime.state.data.approvals;
  assert.equal(records[0].status, 'approved'); assert.equal(records[0].scope, 'session');
  const denied = await fixture(t, { config: { approval: 'on-request' }, ui: { available: true, select: async () => undefined } });
  await assert.rejects(denied.runtime.executor.exec({ cmd: 'printf refused', require_approval: true, yield_time_ms: 1000 }), /denied/);
  await assert.rejects(denied.runtime.executor.exec({ cmd: 'printf refused', require_approval: true, yield_time_ms: 1000 }), /denied/);
  assert.equal(denied.runtime.state.data.approvals.filter(record => record.status === 'denied').length, 2, 'denials are never cached');
  const reopened = await Runtime.create({ root: f.root, config: f.runtime.config, entries: f.persisted, agentDir: f.agentDir, getContext: () => f.context, getUI: () => ({ available: false }) });
  t.after(() => reopened.close());
  assert.equal(reopened.approvals.session.size, 0, 'a fresh runtime starts with an empty in-memory session cache');
  await assert.rejects(reopened.executor.exec({ cmd: 'printf trusted', require_approval: true, yield_time_ms: 1000 }), /Approval unavailable/);
});
test('prefix rules auto-allow matching commands, persist in the agent dir, and isolate by escalation mode', async t => {
  const dialogs = [];
  const f = await fixture(t, { config: { approval: 'on-request' }, ui: { available: true, select: async (_title, labels) => { dialogs.push(labels); return labels[2]; } } });
  const first = await f.runtime.executor.exec({ cmd: 'printf one', require_approval: true, yield_time_ms: 1000 });
  assert.equal(first.exit_code, 0); assert.equal(dialogs.length, 1);
  assert.equal(dialogs[0].length, 4, 'dialog options follow the Codex order: once, session, prefix, deny');
  assert.match(dialogs[0][2], /printf one/, 'the prefix option names the suggested prefix');
  const second = await f.runtime.executor.exec({ cmd: 'printf one more', require_approval: true, yield_time_ms: 1000 });
  assert.equal(second.exit_code, 0); assert.equal(dialogs.length, 1, 'the stored prefix rule auto-allows matching commands without a dialog');
  assert.equal(f.runtime.approvals.rules.rules.length, 1);
  assert.equal(f.runtime.state.data.approvals.at(-1).source, 'prefix-rule');
  assert.deepEqual(JSON.parse(await readFile(execPolicyPath(f.agentDir), 'utf8')).prefixRules, [{ prefix: ['printf', 'one'], escalated: false }]);
  const metachar = approvalOptions({ kind: 'exec', command: 'printf one && printf two', escalated: false });
  assert.deepEqual(metachar.map(option => option.id), ['once', 'session', 'deny'], 'commands with shell operators never offer a prefix');
  assert.deepEqual(approvalOptions({ kind: 'external', name: 'tool' }).map(option => option.id), ['once', 'session', 'deny'], 'external tools get no prefix option');
  assert.deepEqual(suggestPrefix('podman exec -it ctr bash'), ['podman', 'exec', '-it', 'ctr', 'bash']);
  assert.equal(suggestPrefix('bash -c rm -rf /'), null, 'shell scripts never offer a prefix');
  assert.equal(suggestPrefix('rm'), null, 'banned prefixes like rm are filtered');
  assert.equal(suggestPrefix('bash'), null, 'banned interpreter wrappers are filtered');
  const reopened = await Runtime.create({ root: f.root, config: f.runtime.config, entries: [], agentDir: f.agentDir, getContext: () => f.context, getUI: () => ({ available: true, select: async () => { throw Error('must not ask'); } }) });
  t.after(() => reopened.close());
  const persisted = await reopened.executor.exec({ cmd: 'printf one again', require_approval: true, yield_time_ms: 1000 });
  assert.equal(persisted.exit_code, 0, 'prefix rules survive a new runtime like Codex execpolicy.toml');
  const escalated = reopened.executor.exec({ cmd: 'printf one', require_approval: true, sandbox_permissions: 'require_escalated', yield_time_ms: 1000 });
  await assert.rejects(escalated, /must not ask/, 'escalated commands do not reuse non-escalated prefix rules');
});
test('presets control real execution, external approvals and files beyond the workspace', async t => {
  let approvals = 0;
  const f = await fixture(t, { config: { sandboxCommand: '/missing/bwrap' }, ui: { available: true, select: async (_title, options) => { approvals++; return options[0]; } } });
  const outside = await fixture(t); const target = path.join(outside.root, 'external.txt');
  f.runtime.setPermission('Ask for Approval');
  assert.deepEqual(f.runtime.policy.permissions, { approval: 'on-request', sandbox: 'workspace-write', network: false });
  await f.call('write', { path: 'local.txt', content: 'sandboxed workspace' });
  assert.equal(approvals, 0);
  await assert.rejects(f.call('write', { path: target, content: 'blocked' }), /outside/);
  const isolated = await f.runtime.executor.command(['/bin/true']);
  assert.equal(isolated.isolated, true); assert.ok(isolated.argv.includes('--unshare-net'));
  await f.runtime.guardExternal('mcp__service__change', 'root'); assert.equal(approvals, 1);
  const denied = await f.runtime.executor.exec({ cmd: 'echo forbidden', yield_time_ms: 1000 });
  assert.match(denied.error, /ENOENT/);
  f.runtime.setPermission('Full Access');
  assert.deepEqual(f.runtime.policy.permissions, { approval: 'never', sandbox: 'none', network: true });
  await f.call('write', { path: target, content: 'host access' });
  assert.equal(await readFile(target, 'utf8'), 'host access');
  const changed = f.runtime.state.data.changes.at(-1);
  await f.runtime.files.restore(changed.id, [target]);
  await f.runtime.guardExternal('mcp__service__change', 'root');
  const unrestricted = await f.runtime.executor.exec({ cmd: 'printf full-access', workdir: outside.root, require_approval: true, sandbox_permissions: 'require_escalated', yield_time_ms: 1000 });
  assert.equal(unrestricted.exit_code, 0); assert.equal(unrestricted.isolated, false); assert.equal(unrestricted.output, 'full-access');
  assert.equal(approvals, 1, 'Selecting Full Access is sufficient; individual operations must not ask again');
  const search = await f.runtime.executor.command(['rg', '--files'], { readOnly: true });
  assert.equal(search.isolated, false, 'Read-oriented tools follow Full Access without requiring bubblewrap');
  f.runtime.setPermission('Read-Only');
  await assert.rejects(f.call('write', { path: 'local.txt', content: 'no' }), /Read-only/);
  await assert.rejects(f.runtime.executor.exec({ cmd: 'true', sandbox_permissions: 'require_escalated' }), /Read-only/);
  await assert.rejects(f.runtime.guardExternal('mcp__service__change', 'root'), /Read-only/);
  const readonly = await f.runtime.executor.command(['/bin/true']);
  assert.equal(readonly.isolated, true); assert.ok(readonly.argv.includes('--ro-bind')); assert.ok(readonly.argv.includes('--unshare-net'));
});
test('session permission changes reach existing and future descendants while reviewer and plan restrictions remain', async t => {
  const f = await fixture(t);
  const child = f.runtime.threads.spawn('root', { message: 'wait for the next task' }); await f.runtime.threads.live.get(child.id).run;
  f.runtime.setPermission('read-only'); assert.equal(f.runtime.policy.isReadOnly(child.id), true);
  await assert.rejects(f.runtime.tools(child.id, () => f.runtime.threads.context(child.id)).find(tool => tool.name === 'write').execute('write', { path: 'blocked', content: 'no' }), /Read-only/);
  f.runtime.setPermission('full-access'); assert.equal(f.runtime.policy.hasFullAccess(child.id), true);
  const next = f.runtime.threads.spawn(child.id, { message: 'inherited' }); await f.runtime.threads.live.get(next.id).run;
  assert.equal(f.runtime.policy.hasFullAccess(next.id), true);
  const review = f.runtime.threads.spawn('root', { message: 'review', role: 'reviewer' }); await f.runtime.threads.live.get(review.id).run;
  assert.equal(f.runtime.policy.hasFullAccess(review.id), false); assert.equal(f.runtime.policy.isReadOnly(review.id), true);
  await assert.rejects(f.runtime.executor.exec({ cmd: 'true', sandbox_permissions: 'require_escalated' }, review.id), /Read-only/);
  await f.runtime.setMode('plan'); assert.equal(f.runtime.policy.isReadOnly(), true); assert.equal(f.runtime.policy.hasFullAccess(), false);
  await assert.rejects(f.call('write', { path: 'blocked', content: 'no' }), /Read-only/);
});
test('permission changes cannot race active tools, queued or suspended agents, approval dialogs or background jobs', async t => {
  const confirmation = deferred();
  const f = await fixture(t, { config: { approval: 'always', concurrency: 1 }, ui: { available: true, select: async (_title, options) => { await confirmation.promise; return options[0]; } } });
  const pendingWrite = f.call('write', { path: 'file', content: 'authorized under original policy' });
  while (!f.runtime.state.data.approvals.length) await pause(1);
  assert.throws(() => f.runtime.setPermission('full-access'), /停止/);
  confirmation.resolve(true); await pendingWrite;
  f.runtime.setPermission('full-access');
  const job = await f.runtime.executor.exec({ cmd: 'read line', yield_time_ms: 5 });
  assert.equal(job.running, true); assert.throws(() => f.runtime.setPermission('read-only'), /停止/);
  await f.runtime.executor.write({ process_id: job.process_id, cancel: true, yield_time_ms: 1000 }, 'root');
  const signal = new AbortController(); await f.runtime.scheduler.acquire('root');
  const queued = f.runtime.scheduler.acquire('worker', signal.signal);
  assert.throws(() => f.runtime.setPermission('read-only'), /停止/); signal.abort(); await assert.rejects(queued); f.runtime.scheduler.release('root');
  f.runtime.setPermission('read-only');
  assert.equal(f.runtime.policy.preset.id, 'read-only');
});
test('selected permissions persist in the branch; changing one branch or a new session does not change the config', async t => {
  const f = await fixture(t); const configBefore = JSON.stringify(f.runtime.config);
  f.runtime.setPermission('read-only'); const readBranch = structuredClone(f.persisted);
  f.runtime.setPermission('full-access');
  const restore = entries => Runtime.create({ root: f.root, config: f.runtime.config, entries, getContext: () => f.context, getUI: () => ({ available: false }) });
  const readonly = await restore(readBranch), full = await restore(f.persisted), fresh = await restore([]);
  t.after(async () => { await readonly.close(); await full.close(); await fresh.close(); });
  assert.equal(readonly.policy.preset.id, 'read-only'); assert.equal(full.policy.preset.id, 'full-access'); assert.equal(fresh.state.data.permissionPreset, null);
  assert.equal(JSON.stringify(f.runtime.config), configBefore);
  assert.equal(new State(() => {}, readBranch).summary().permissionPreset, 'read-only');
});
